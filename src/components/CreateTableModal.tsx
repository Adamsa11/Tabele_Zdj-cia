import React, { useState } from 'react';
import { ColumnDataType, ColumnMeta, TableMeta } from '../types';
import { registerCustomTable } from '../lib/supabaseClient';
import { Plus, Trash2, X, Code, Copy, Check, Table } from 'lucide-react';

interface CreateTableModalProps {
  isOpen: boolean;
  onClose: () => void;
  onTableCreated: (tableName: string) => void;
  onToast: (type: 'success' | 'error' | 'info', title: string, message?: string) => void;
}

export const CreateTableModal: React.FC<CreateTableModalProps> = ({
  isOpen,
  onClose,
  onTableCreated,
  onToast
}) => {
  const [tableName, setTableName] = useState('');
  const [columns, setColumns] = useState<ColumnMeta[]>([
    { name: 'id', dataType: 'number', isPrimary: true, isNullable: false },
    { name: 'title', dataType: 'text', isPrimary: false, isNullable: false },
    { name: 'image_url', dataType: 'image', isPrimary: false, isNullable: true },
    { name: 'created_at', dataType: 'datetime', isPrimary: false, isNullable: false }
  ]);
  const [showSql, setShowSql] = useState(false);
  const [copiedSql, setCopiedSql] = useState(false);

  if (!isOpen) return null;

  const handleAddColumn = () => {
    setColumns(prev => [
      ...prev,
      {
        name: `column_${prev.length + 1}`,
        dataType: 'text',
        isPrimary: false,
        isNullable: true
      }
    ]);
  };

  const handleRemoveColumn = (index: number) => {
    if (columns.length <= 1) return;
    setColumns(prev => prev.filter((_, i) => i !== index));
  };

  const handleColumnChange = (index: number, key: keyof ColumnMeta, val: any) => {
    setColumns(prev => {
      const copy = [...prev];
      copy[index] = { ...copy[index], [key]: val };
      return copy;
    });
  };

  // Generate clean PostgreSQL DDL
  const generateSql = (): string => {
    const safeName = tableName.trim().toLowerCase().replace(/[^a-z0-9_]/g, '_') || 'my_table';
    const colDefs = columns.map(col => {
      let pgType = 'TEXT';
      if (col.dataType === 'number') pgType = col.isPrimary ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY' : 'NUMERIC';
      else if (col.dataType === 'boolean') pgType = 'BOOLEAN DEFAULT FALSE';
      else if (col.dataType === 'datetime') pgType = 'TIMESTAMPTZ DEFAULT NOW()';
      else if (col.dataType === 'json') pgType = 'JSONB';
      else if (col.dataType === 'uuid') pgType = 'UUID DEFAULT gen_random_uuid()';

      const pkPart = col.isPrimary && !pgType.includes('IDENTITY') ? ' PRIMARY KEY' : (col.isPrimary ? ' PRIMARY KEY' : '');
      const nullPart = !col.isNullable && !col.isPrimary ? ' NOT NULL' : '';
      return `  "${col.name}" ${pgType}${pkPart}${nullPart}`;
    });

    return `CREATE TABLE IF NOT EXISTS public."${safeName}" (\n${colDefs.join(',\n')}\n);\n\n-- Włącz uprawnienia odczytu/zapisu dla RLS lub roli anon:\nALTER TABLE public."${safeName}" ENABLE ROW LEVEL SECURITY;\nCREATE POLICY "Dostęp publiczny" ON public."${safeName}" FOR ALL USING (true);`;
  };

  const handleSave = () => {
    const cleanName = tableName.trim().toLowerCase().replace(/[^a-z0-9_]/g, '_');
    if (!cleanName) {
      alert('Podaj poprawną nazwę tabeli.');
      return;
    }

    const newTable: TableMeta = {
      name: cleanName,
      schema: 'public',
      rowCount: 0,
      columns,
      isCustom: true
    };

    registerCustomTable(newTable);
    onToast('success', 'Utworzono tabelę', `Tabela "${cleanName}" została dodana do aplikacji.`);
    onTableCreated(cleanName);
    onClose();
  };

  const handleCopySql = () => {
    navigator.clipboard.writeText(generateSql());
    setCopiedSql(true);
    setTimeout(() => setCopiedSql(false), 2000);
    onToast('info', 'Skopiowano kod SQL', 'Możesz wkleić go w Supabase SQL Editor.');
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/80 backdrop-blur-sm p-4 animate-in fade-in duration-150">
      <div className="relative w-full max-w-2xl max-h-[90vh] flex flex-col bg-slate-900 border border-slate-800 rounded-xl overflow-hidden shadow-2xl">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-800 bg-slate-950/70">
          <div className="flex items-center gap-3">
            <div className="p-2 rounded-lg bg-emerald-500/10 text-emerald-400 border border-emerald-500/20">
              <Table className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-base font-semibold text-slate-100">Utwórz nową tabelę / schemat</h3>
              <p className="text-xs text-slate-400">Zdefiniuj strukturę kolumn i typów dla Supabase</p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="p-1.5 text-slate-400 hover:text-white rounded-lg hover:bg-slate-800 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content */}
        <div className="flex-1 overflow-y-auto p-6 space-y-5">
          {/* Table Name */}
          <div>
            <label className="text-xs font-semibold uppercase tracking-wider text-slate-400 block mb-1.5">
              Nazwa tabeli (PostgreSQL)
            </label>
            <input
              type="text"
              placeholder="np. products, invoices, articles"
              value={tableName}
              onChange={e => setTableName(e.target.value)}
              className="w-full px-3 py-2 text-xs font-mono bg-slate-950 border border-slate-800 rounded-lg text-slate-200 placeholder-slate-400 focus:outline-none focus:border-emerald-500"
            />
          </div>

          {/* Columns Designer */}
          <div>
            <div className="flex items-center justify-between mb-2">
              <label className="text-xs font-semibold uppercase tracking-wider text-slate-400">
                Kolumny tabeli ({columns.length})
              </label>
              <button
                type="button"
                onClick={handleAddColumn}
                className="flex items-center gap-1 px-2.5 py-1 text-xs text-emerald-400 hover:text-emerald-300 bg-emerald-950/40 hover:bg-emerald-950/70 border border-emerald-500/30 rounded-lg transition-colors"
              >
                <Plus className="w-3.5 h-3.5" />
                <span>Dodaj kolumnę</span>
              </button>
            </div>

            <div className="space-y-2 max-h-64 overflow-y-auto pr-1">
              {columns.map((col, index) => (
                <div
                  key={index}
                  className="flex items-center gap-2 p-2 bg-slate-950/60 border border-slate-800 rounded-lg"
                >
                  {/* Name */}
                  <input
                    type="text"
                    value={col.name}
                    onChange={e => handleColumnChange(index, 'name', e.target.value)}
                    placeholder="nazwa_kolumny"
                    className="flex-1 px-2.5 py-1.5 text-xs font-mono bg-slate-900 border border-slate-800 rounded text-slate-200 focus:outline-none focus:border-emerald-500"
                  />

                  {/* Data Type */}
                  <select
                    value={col.dataType}
                    onChange={e => handleColumnChange(index, 'dataType', e.target.value as ColumnDataType)}
                    className="px-2 py-1.5 text-xs bg-slate-900 border border-slate-800 rounded text-slate-200 focus:outline-none focus:border-emerald-500"
                  >
                    <option value="text">text (tekst)</option>
                    <option value="number">number (liczba)</option>
                    <option value="image">image (zdjęcie / URL)</option>
                    <option value="boolean">boolean (prawda/fałsz)</option>
                    <option value="datetime">datetime (data i czas)</option>
                    <option value="json">json (obiekt/tablica)</option>
                    <option value="uuid">uuid (unikalny ID)</option>
                  </select>

                  {/* Primary Key Check */}
                  <label className="flex items-center gap-1 text-[11px] text-slate-400 cursor-pointer px-1">
                    <input
                      type="checkbox"
                      checked={!!col.isPrimary}
                      onChange={e => handleColumnChange(index, 'isPrimary', e.target.checked)}
                      className="rounded border-slate-800 text-emerald-500 focus:ring-0"
                    />
                    <span>PK</span>
                  </label>

                  {/* Nullable Check */}
                  <label className="flex items-center gap-1 text-[11px] text-slate-400 cursor-pointer px-1">
                    <input
                      type="checkbox"
                      checked={!!col.isNullable}
                      onChange={e => handleColumnChange(index, 'isNullable', e.target.checked)}
                      className="rounded border-slate-800 text-emerald-500 focus:ring-0"
                    />
                    <span>Null</span>
                  </label>

                  {/* Remove Button */}
                  <button
                    type="button"
                    onClick={() => handleRemoveColumn(index)}
                    disabled={columns.length <= 1}
                    className="p-1.5 text-slate-400 hover:text-rose-400 disabled:opacity-30 rounded transition-colors"
                  >
                    <Trash2 className="w-3.5 h-3.5" />
                  </button>
                </div>
              ))}
            </div>
          </div>

          {/* Toggle SQL preview */}
          <div>
            <button
              type="button"
              onClick={() => setShowSql(!showSql)}
              className="text-xs text-slate-400 hover:text-slate-200 flex items-center gap-1.5"
            >
              <Code className="w-3.5 h-3.5 text-emerald-400" />
              <span>{showSql ? 'Ukryj kod PostgreSQL DDL' : 'Pokaż kod PostgreSQL DDL dla Supabase SQL Editor'}</span>
            </button>

            {showSql && (
              <div className="mt-2 relative">
                <pre className="p-3 bg-slate-950 border border-slate-800 rounded-lg text-[11px] font-mono text-emerald-400 overflow-x-auto">
                  {generateSql()}
                </pre>
                <button
                  type="button"
                  onClick={handleCopySql}
                  className="absolute top-2 right-2 px-2 py-1 text-[11px] bg-slate-800 hover:bg-slate-700 text-slate-200 rounded flex items-center gap-1 border border-slate-700"
                >
                  {copiedSql ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                  <span>{copiedSql ? 'Skopiowano' : 'Kopiuj'}</span>
                </button>
              </div>
            )}
          </div>
        </div>

        {/* Footer */}
        <div className="flex items-center justify-between px-6 py-4 border-t border-slate-800 bg-slate-950/70">
          <button
            type="button"
            onClick={onClose}
            className="px-4 py-2 text-xs font-medium text-slate-300 hover:text-white bg-slate-800 hover:bg-slate-700 rounded-lg transition-colors"
          >
            Anuluj
          </button>
          <button
            type="button"
            onClick={handleSave}
            className="px-5 py-2 text-xs font-medium text-white bg-emerald-600 hover:bg-emerald-500 rounded-lg transition-colors shadow-sm"
          >
            Utwórz tabelę w aplikacji
          </button>
        </div>
      </div>
    </div>
  );
};
